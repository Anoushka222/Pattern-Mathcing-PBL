def bad_character_table(pattern):
    table = {}
    for i in range(len(pattern)):
        table[pattern[i]] = i
    return table

def boyer_moore(text, pattern):
    n = len(text)
    m = len(pattern)

    if m == 0:
        return 0

    table = bad_character_table(pattern)
    s = 0

    while s <= n - m:
        j = m - 1

        while j >= 0 and pattern[j] == text[s + j]:
            j -= 1

        if j < 0:
            return s
        else:
            char = text[s + j]
            s += max(1, j - table.get(char, -1))

    return -1

