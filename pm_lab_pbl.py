def boyer_moore_search_all(text, pattern):
    n = len(text)
    m = len(pattern)
    if m == 0:
        return []

    table = bad_character_table(pattern)
    s = 0
    occurrences = []
    comparisons = 0
    shifts = 0

    print(f"Searching for pattern...\n")

    while s <= n - m:
        j = m - 1

        print(f"Current position: {s}")
        while j >= 0:
            comparisons += 1
            text_char = text[s + j]
            pat_char = pattern[j]
            if pat_char != text_char:
                print(f"Comparing: {pat_char} with {text_char}")
                print("Mismatch found!")
                print(f"Bad character: {text_char}")
                shift_val = max(1, j - table.get(text_char, -1))
                print(f"Shifting pattern by: {shift_val}")
                print("--------------------------------")
                s += shift_val
                shifts += 1
                break
            j -= 1
        else:
            # Pattern matched
            print(f"Pattern matched at index: {s}")
            print("--------------------------------")
            occurrences.append(s)
            # Shift by 1 or check next alignment
            shift_val = m - table.get(text[s + m - 1], -1) if s + m < n else 1
            s += max(1, shift_val)
            shifts += 1

    print("========== FINAL RESULTS ==========")
    print(f"Pattern found at positions: {occurrences}")
    print(f"Total occurrences: {len(occurrences)}")
    print(f"Total character comparisons: {comparisons}")
    print(f"Total shifts: {shifts}")
    return occurrences

